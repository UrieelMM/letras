#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const OUTPUT_DIR = path.join(ROOT, 'src/assets/fonts');
const CSS_PATH = path.join(ROOT, 'src/fonts.css');
const USER_AGENT = 'Mozilla/5.0 AppleWebKit/537.36 Chrome/124 Safari/537.36';

const families = [
  'Inter:wght@300;400;500;600;700;800;900',
  'Manrope:wght@400;500;600;700;800',
  'Poppins:wght@300;400;500;600;700;800;900',
  'Montserrat:wght@300;400;500;600;700;800;900',
  'Nunito:wght@300;400;600;700;800;900',
  'Raleway:wght@300;400;500;600;700;800;900',
  'Quicksand:wght@400;500;600;700',
  'Oswald:wght@300;400;500;600;700',
  'Bebas+Neue',
  'Anton',
  'Archivo+Black',
  'Righteous',
  'Fredoka:wght@400;500;600;700',
  'Orbitron:wght@400;500;700;900',
  'Audiowide',
  'Bungee',
  'Monoton',
  'Press+Start+2P',
  'Permanent+Marker',
  'Playfair+Display:wght@400;500;600;700;800;900',
  'Merriweather:wght@300;400;700;900',
  'Lobster',
  'Pacifico',
  'Dancing+Script:wght@400;500;600;700',
  'Caveat:wght@400;500;600;700',
  'Cinzel:wght@700',
];

await mkdir(OUTPUT_DIR, { recursive: true });
const output = ['/* Generated by scripts/download-fonts.mjs. Local Latin subsets only. */'];

for (const family of families) {
  const endpoint = `https://fonts.googleapis.com/css2?family=${family}&display=swap`;
  const response = await fetch(endpoint, { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) throw new Error(`Google Fonts respondió ${response.status} para ${family}`);
  const css = await response.text();
  const blocks = css.match(/@font-face\s*{[^}]+}/g) ?? [];
  const latinBlocks = blocks.filter((block) => (
    !block.includes('unicode-range') || block.includes('U+0000-00FF')
  ));

  for (const block of latinBlocks) {
    const url = block.match(/url\((https:[^)]+)\)/)?.[1];
    if (!url) continue;
    const hash = createHash('sha256').update(url).digest('hex').slice(0, 12);
    const filename = `${family.split(':')[0].replace(/\+/g, '-').toLowerCase()}-${hash}.woff2`;
    const fontResponse = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
    if (!fontResponse.ok) throw new Error(`No se pudo descargar ${url}`);
    await writeFile(path.join(OUTPUT_DIR, filename), Buffer.from(await fontResponse.arrayBuffer()));
    output.push(block.replace(url, `./assets/fonts/${filename}`));
  }
}

await writeFile(CSS_PATH, `${output.join('\n\n')}\n`, 'utf8');
console.log(`Fuentes locales generadas en ${path.relative(ROOT, OUTPUT_DIR)}`);
